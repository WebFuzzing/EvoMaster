package org.evomaster.e2etests.spring.openapi.v3.arazzo

import com.foo.rest.examples.spring.openapi.v3.arazzo.ArazzoPetCouponsController
import org.evomaster.core.problem.rest.data.HttpVerb
import org.evomaster.e2etests.spring.openapi.v3.SpringTestBase
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeAll
import org.junit.jupiter.api.Test

class ArazzoEMTest : SpringTestBase() {

    companion object {
        private const val ARAZZO_LOCATION = "src/main/resources/static/pet-coupons-arazzo.yaml"

        @BeforeAll
        @JvmStatic
        fun init() {
            initClass(ArazzoPetCouponsController())
        }
    }

    @Test
    fun testRunEMWithArazzoWorkflowSampling() {
        runTestHandlingFlakyAndCompilation(
            "ArazzoEM",
            "org.foo.ArazzoEM",
            50,
        ) { args ->
            setOption(args, "enableArazzoWorkflowSampling", "true")
            setOption(args, "arazzoLocation", ARAZZO_LOCATION)
            setOption(args, "probOfArazzoSampling", "1.0")
            // SmartSampling is disabled to ensure that the created individuals were generated by Arazzo.
            setOption(args, "probOfSmartSampling", "0.0")

            val solution = initAndRun(args)

            assertTrue(solution.individuals.size >= 1)

            // apply-coupon: findPetsByTags -> getPetCoupons -> placeOrder
            assertHasAtLeastOne(solution, HttpVerb.GET, 200, "/pet/findByTags", null)
            assertHasAtLeastOne(solution, HttpVerb.GET, 200, "/pet/{petId}/coupons", null)
            assertHasAtLeastOne(solution, HttpVerb.POST, 200, "/store/order", null)

            // buy-available-pet: findPetsByStatus -> placeOrder
            assertHasAtLeastOne(solution, HttpVerb.GET, 200, "/pet/findByStatus", null)
        }
    }
}
