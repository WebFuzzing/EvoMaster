package org.evomaster.client.java.controller.api.dto.database.execution;

import org.evomaster.client.java.controller.api.dto.database.operations.DynamoDbAttributeValueDto;
import org.evomaster.client.java.controller.api.dto.database.operations.DynamoDbScalarTypeDto;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Equality constraints from a successful DynamoDB read that returned no matching item.
 */
public class DynamoDbFailedQuery {

    public String tableName;
    public List<DynamoDbAttributeValueDto> attributes = new ArrayList<>();

    /** Primary-key attributes absent from the inferred item, to be generated by core in schema order. */
    public Map<String, DynamoDbScalarTypeDto> missingPrimaryKeyAttributes = new LinkedHashMap<>();

    public DynamoDbFailedQuery() {
    }

    /**
     * Creates a failed-query description.
     *
     * @param tableName target table
     * @param attributes equality-constrained attributes
     */
    public DynamoDbFailedQuery(String tableName, List<DynamoDbAttributeValueDto> attributes) {
        this.tableName = tableName;
        this.attributes = new ArrayList<>(attributes);
    }

    /**
     * Creates a failed-query description with the key attributes that core must generate.
     *
     * @param tableName target table
     * @param attributes inferred query and template values
     * @param missingPrimaryKeyAttributes missing key names and supported scalar types
     */
    public DynamoDbFailedQuery(String tableName, List<DynamoDbAttributeValueDto> attributes,
                               Map<String, DynamoDbScalarTypeDto> missingPrimaryKeyAttributes) {
        this(tableName, attributes);
        this.missingPrimaryKeyAttributes = new LinkedHashMap<>(missingPrimaryKeyAttributes);
    }
}
